import { build } from 'vite';
import { mkdir, copyFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const dist = path.resolve(root, 'dist');
if (path.dirname(dist) !== root || path.basename(dist) !== 'dist') throw new Error('Invalid build output path');
await rm(dist, { recursive: true, force: true });
await mkdir('dist', { recursive: true });
await build({ configFile: false, publicDir: false, build: { emptyOutDir: false, outDir: 'dist', rollupOptions: { input: ['sidepanel.html', 'options.html', 'phrases.html', 'research.html'] } } });
await build({ configFile: false, publicDir: false, build: { emptyOutDir: false, outDir: 'dist', lib: { entry: 'src/background.ts', formats: ['es'], fileName: () => 'background.js' }, rollupOptions: { output: { inlineDynamicImports: true } } } });
await build({ configFile: false, publicDir: false, build: { emptyOutDir: false, outDir: 'dist', lib: { entry: 'src/content.ts', formats: ['iife'], name: 'ReadingAssistant', fileName: () => 'content.js' }, rollupOptions: { output: { inlineDynamicImports: true } } } });
await copyFile('public/manifest.json', 'dist/manifest.json');
await copyFile('LICENSE', 'dist/LICENSE');
await copyFile('node_modules/@mozilla/readability/LICENSE.md', 'dist/READABILITY-LICENSE.md');
await copyFile('node_modules/typescript/LICENSE.txt', 'dist/LICENSE-APACHE-2.0.txt');
await copyFile('node_modules/marked/LICENSE', 'dist/MARKED-LICENSE.txt');
await copyFile('node_modules/dompurify/LICENSE', 'dist/DOMPURIFY-LICENSE.txt');
await copyFile('node_modules/dompurify/LICENSE-MPL', 'dist/DOMPURIFY-LICENSE-MPL.txt');
await copyFile('THIRD_PARTY_NOTICES.md', 'dist/THIRD_PARTY_NOTICES.md');
